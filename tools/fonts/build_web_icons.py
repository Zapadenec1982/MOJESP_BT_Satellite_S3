#!/usr/bin/env python3
"""Build the web UI's icon font: the panel's Material Symbols Rounded, cut to the icons the web uses.

The web wears the panel's icons: the same variable font,
fetched and pinned by symbols.lock exactly as build_fonts.py does for the panel, pinned to
weight 400, GRAD 0 and optical size 24 like the panel's faces. FILL stays a live axis, so one
font draws both the outlined and the filled face (`font-variation-settings: 'FILL' 1`).

The web asks for a glyph by its codepoint, not by its ligature name: a ligature subset would
have to keep every icon whose name can be spelled with a-z, 0-9 and "_" — all of them.

Input   webui/src/lib/icon_names.json          the names, by Material's own spelling
Output  webui/src/lib/icon_codepoints.js       name → codepoint, for Icon.svelte
        webui/src/styles/icons.css             @font-face with the font inline (woff2, base64):
                                               no second request, and no reliance on the
                                               device's static server knowing font/woff2

Output is committed; the web build needs neither the network nor fontTools. Re-run after
changing icon_names.json and commit both outputs:

    python tools/fonts/build_web_icons.py

Needs fontTools and brotli (woff2) in the python that runs it.
"""

import base64
import io
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import build_fonts  # noqa: E402  (same directory: fetch_symbols, load_codepoints, paths)

ROOT = HERE.parent.parent
NAMES = ROOT / "webui" / "src" / "lib" / "icon_names.json"
OUT_JS = ROOT / "webui" / "src" / "lib" / "icon_codepoints.js"
OUT_CSS = ROOT / "webui" / "src" / "styles" / "icons.css"
FAMILY = "P4 Symbols"


def main():
    try:
        from fontTools.ttLib import TTFont
        from fontTools.varLib import instancer
        from fontTools import subset
    except ImportError:
        sys.exit("needs fontTools and brotli: pip install fonttools brotli")

    names = json.loads(NAMES.read_text(encoding="utf-8"))
    if names != sorted(set(names)):
        sys.exit(f"{NAMES.name}: keep it sorted and without duplicates")

    build_fonts.fetch_symbols()
    table = build_fonts.load_codepoints()
    missing = [n for n in names if n not in table]
    if missing:
        sys.exit(f"not in Material Symbols Rounded: {', '.join(missing)}")
    cps = {n: table[n] for n in names}

    font = TTFont(str(build_fonts.SYMBOLS_VAR))
    font = instancer.instantiateVariableFont(font, {"wght": 400, "GRAD": 0, "opsz": 24})
    # The instancer leaves gvar lazily bound to the old glyph set; the subsetter then asks it
    # for glyphs it no longer resolves (KeyError). A round trip through bytes settles it.
    staged = io.BytesIO()
    font.save(staged)
    staged.seek(0)
    font = TTFont(staged)

    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = []          # codepoints only: no ligatures, no GSUB
    opts.hinting = False
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6]   # keep the licence notice and the family name
    opts.notdef_outline = True
    opts.glyph_names = False
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=sorted(set(cps.values())))
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    woff2 = buf.getvalue()

    js = ["// GENERATED by tools/fonts/build_web_icons.py from webui/src/lib/icon_names.json - do not edit.",
          "// Material Symbols Rounded (Apache 2.0): name -> codepoint of the glyph in icons.css.",
          "export default {"]
    js += [f"  {n}: 0x{cps[n]:X}," for n in names]
    js.append("};")
    OUT_JS.write_text("\n".join(js) + "\n", encoding="utf-8")

    css = [
        "/* GENERATED by tools/fonts/build_web_icons.py - do not edit.",
        f"   Material Symbols Rounded (Apache 2.0, google/material-design-icons), {len(names)} icons,",
        "   weight 400, GRAD 0, opsz 24 like the panel; FILL kept as an axis. */",
        "@font-face {",
        f"  font-family: '{FAMILY}';",
        "  font-style: normal;",
        "  font-weight: 400;",
        "  font-display: block;",
        f"  src: url(data:font/woff2;base64,{base64.b64encode(woff2).decode('ascii')}) format('woff2');",
        "}",
    ]
    OUT_CSS.write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"{len(names)} icons, woff2 {len(woff2)} bytes -> {OUT_CSS.relative_to(ROOT)}, {OUT_JS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
