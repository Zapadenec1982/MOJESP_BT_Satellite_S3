"""Generate components/radio_catalog/src/countries.inc: ISO 3166-1 alpha-2 -> name in four languages.

The station catalog lists countries by code (Radio Browser's /json/countrycodes) and its own
English names are long ("The United Kingdom Of Great Britain And Northern Ireland"), so the
screen names them from Unicode CLDR instead: the short form where CLDR has one ("США", "USA"),
unless that form is an abbreviation with a full stop ("Wlk. Bryt.") — a list reads better with
the name written out. One column per language in ui.lang's order — uk, en, de, pl — and the
codes are the Ukrainian table's; a name a language lacks is the English one, then the Ukrainian.

Pinned to one CLDR release so the table only changes when someone means it to:

    python tools/gen_country_names.py        # downloads CLDR_TAG's territories.json for each language
    python tools/gen_country_names.py DIR    # or reads DIR/<lang>.json from disk

Data: Unicode CLDR, Unicode License v3 (https://www.unicode.org/license.txt).
"""

import json
import os
import sys
import urllib.request

CLDR_TAG = "48.0.0"
LANGS = ("uk", "en", "de", "pl")      # ui.lang 0..3
URL = ("https://raw.githubusercontent.com/unicode-org/cldr-json/%s/cldr-json/"
       "cldr-localenames-full/main/%%s/territories.json" % CLDR_TAG)
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "components", "radio_catalog", "src", "countries.inc")


def load(lang, directory=None):
    if directory:
        with open(os.path.join(directory, "%s.json" % lang), encoding="utf-8") as f:
            data = json.load(f)
    else:
        with urllib.request.urlopen(URL % lang, timeout=30) as r:
            data = json.loads(r.read().decode("utf-8"))
    return data["main"][lang]["localeDisplayNames"]["territories"]


def names(territories):
    """{code: name} for the two-letter codes, the short form winning unless it abbreviates."""
    table = {}
    for key, name in territories.items():
        code = key.split("-")[0]
        if len(code) != 2 or not code.isalpha() or not code.isupper():
            continue                      # regions ("150") and private codes
        if key.endswith("-alt-short"):
            if "." not in name:
                table[code] = name
        elif "-" not in key and code not in table:
            table[code] = name            # the full name, unless a short form came first
    return table


# CLDR spells the Ukrainian apostrophe as U+02BC MODIFIER LETTER APOSTROPHE ("Вʼєтнам"), which the
# panel's faces do not carry (tools/fonts/build_fonts.py): it was a box on the glass. U+2019, the
# typographic apostrophe, is in every face and reads the same.
GLYPH_STAND_INS = {"\u02bc": "\u2019"}


def c_string(s):
    for a, b in GLYPH_STAND_INS.items():
        s = s.replace(a, b)
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main(argv):
    directory = argv[1] if len(argv) > 1 else None
    tables = {lang: names(load(lang, directory)) for lang in LANGS}
    lines = [
        "// Generated by tools/gen_country_names.py from Unicode CLDR %s — do not edit." % CLDR_TAG,
        "// Data: Unicode CLDR, Unicode License v3 (https://www.unicode.org/license.txt).",
        "// ISO 3166-1 alpha-2 code -> short name in uk, en, de, pl (ui.lang's order), sorted by code",
        "// for a binary search.",
    ]
    for code in sorted(tables["uk"]):
        row = [tables[lang].get(code) or tables["en"].get(code) or tables["uk"][code] for lang in LANGS]
        lines.append('{"%s", {%s}},' % (code, ", ".join('"%s"' % c_string(n) for n in row)))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d countries in %d languages -> %s" % (len(tables["uk"]), len(LANGS), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main(sys.argv)
