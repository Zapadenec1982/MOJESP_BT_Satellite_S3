#!/usr/bin/env python3
"""
web_tokens.py — the panel's Material 3 colour roles as CSS custom properties for the web UI.

The web UI wears the panel's colours (docs/PLAN_WEBUI_2026-10-11.md §3), and the panel's
colours live in one place: the THEMES table in modules/ui_lvgl/src/ui_m3.cpp, whose role
order is struct Colors in ui_m3.h. This script reads both and writes
webui/src/styles/m3_schemes.css — one block per scheme, selected by data-scheme="N" on
<html>, N being ui.theme. Nothing is typed twice, so the schemes cannot drift apart:
tools/tests/test_webui_tokens.py fails when the CSS is older than the table.

    python tools/ui/web_tokens.py           # rewrite the CSS
    python tools/ui/web_tokens.py --check   # exit 1 if it is out of date
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "modules" / "ui_lvgl" / "src" / "ui_m3.h"
TABLE = ROOT / "modules" / "ui_lvgl" / "src" / "ui_m3.cpp"
OUT = ROOT / "webui" / "src" / "styles" / "m3_schemes.css"


def roles(header_text):
    """The colour roles in declaration order, from struct Colors."""
    body = re.search(r"struct Colors\s*\{(.*?)\};", header_text, re.S)
    if not body:
        raise SystemExit("struct Colors not found in ui_m3.h")
    names = re.findall(r"uint32_t\s+(\w+)\s*;", body.group(1))
    if not names:
        raise SystemExit("struct Colors has no uint32_t members")
    return names


def schemes(table_text, n_roles):
    """[(name, [0xRRGGBB, ...]), ...] in table order, i.e. by ui.theme value."""
    consts = {m.group(1): int(m.group(2), 16)
              for m in re.finditer(r"constexpr\s+uint32_t\s+(\w+)\s*=\s*0x([0-9A-Fa-f]{6})\s*;", table_text)}
    table = re.search(r"THEMES\s*\[[^\]]*\]\s*=\s*\{(.*?)\n\};", table_text, re.S)
    if not table:
        raise SystemExit("THEMES table not found in ui_m3.cpp")
    out = []
    for m in re.finditer(r'\{\s*"([^"]+)"\s*,\s*\{([^}]*)\}', table.group(1)):
        values = []
        for tok in (t.strip() for t in m.group(2).split(",")):
            if not tok:
                continue
            if tok.lower().startswith("0x"):
                values.append(int(tok, 16))
            elif tok in consts:
                values.append(consts[tok])
            else:
                raise SystemExit(f"scheme {m.group(1)}: unknown colour {tok!r}")
        if len(values) != n_roles:
            raise SystemExit(f"scheme {m.group(1)}: {len(values)} colours for {n_roles} roles")
        out.append((m.group(1), values))
    if not out:
        raise SystemExit("THEMES table has no schemes")
    return out


def render(header_text, table_text):
    names = roles(header_text)
    lines = [
        "/* GENERATED by tools/ui/web_tokens.py from modules/ui_lvgl/src/ui_m3.cpp - do not edit.",
        "   One block per scheme; data-scheme on <html> is ui.theme, the panel's own setting. */",
    ]
    for idx, (name, values) in enumerate(schemes(table_text, len(names))):
        selector = f':root[data-scheme="{idx}"]'
        if idx == 0:
            selector = f":root, {selector}"
        lines.append("")
        lines.append(f"/* {idx}: {name} */")
        lines.append(selector + " {")
        for role, value in zip(names, values):
            lines.append(f"  --{role.replace('_', '-')}: #{value:06X};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render(HEADER.read_text(encoding="utf-8"), TABLE.read_text(encoding="utf-8"))
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python tools/ui/web_tokens.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
